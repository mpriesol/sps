const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const base = process.env.SPS_E2E_URL || 'http://127.0.0.1:8765/sps/';
const output = path.resolve(__dirname, '../../test-results/browser');

(async () => {
  await fs.mkdir(output, { recursive: true });
  const photoFixture = path.join(output, 'test-parcel.svg');
  await fs.writeFile(photoFixture, '<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600"><rect width="800" height="600" fill="#f1f3ef"/><rect x="100" y="100" width="600" height="400" rx="10" fill="#b99158"/><path d="M400 100V500" stroke="#e7cca3" stroke-width="60"/><rect x="160" y="160" width="170" height="110" fill="white"/><text x="195" y="235" font-family="sans-serif" font-size="65" font-weight="bold">01</text></svg>');
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const shot = name => page.screenshot({path: path.join(output, `${name}.png`), fullPage:true});
  const step = message => process.stdout.write(message+'\n');
  const snapshot = () => page.evaluate(async () => (await fetch('./api/warehouse')).json());
  const waitParcel = async (number, condition) => {
    await page.waitForFunction(async ({number,condition}) => {
      const data = await (await fetch('./api/warehouse')).json();
      const p = data.parcels.find(p=>p.number===number);
      return p && Object.entries(condition).every(([k,v])=>p[k]===v);
    }, {number,condition});
  };
  const waitReady = async view => {
    await page.waitForFunction(expected => {
      const work = document.querySelector('#work-view');
      return work && !work.hidden && work.getAttribute('aria-busy') === 'false' && (!expected || work.dataset.view === expected);
    }, view || null);
  };
  const openView = async view => {
    await waitReady();
    await page.locator(`#nav-${view}`).click();
    await waitReady(view);
  };
  const scan = async code => {
    await page.locator('#manual-code').fill(code);
    await page.locator('#manual-add').click();
  };
  try {
    await page.goto(base);
    await page.locator('#app-password').fill('local-e2e-password-only');
    await page.locator('#login-button').click();
    await page.locator('#nav-locations').waitFor({state:'visible'});
    step('Login works under /sps prefix.');
    await openView('locations');
    await page.locator('#rack-name').fill('A');
    await page.locator('#shelf-count').fill('2');
    await page.locator('#place-count').fill('0');
    await page.getByRole('button',{name:'Vytvoriť regál',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.location-row').length===2);
    let data=await snapshot();
    const a1=data.locations.find(p=>p.name==='A1'), a2=data.locations.find(p=>p.name==='A2');
    assert(a1 && a2 && a1.barcode!==a2.barcode);
    await page.getByRole('button',{name:'Pridať samostatné miesto',exact:true}).click();
    await page.locator('#special-name').fill('Pult');
    await page.getByRole('button',{name:'Vytvoriť miesto',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.location-row').length===3);
    step('Rack and standalone location creation work.');
    await openView('receipt');
    await page.locator('#receipt-place').check();
    await scan('DEMO00000001');
    await page.waitForFunction(()=>document.querySelector('#receipt-courier').options.length===3);
    await page.locator('#receipt-courier').selectOption('2');
    await page.locator('#courier-warning').waitFor({state:'visible'});
    await scan(a1.barcode); await waitParcel('DEMO00000001',{location_id:a1.id});
    await scan('DEMO00000002');
    await page.waitForFunction(()=>document.querySelector('#selected-count').textContent==='2');
    await scan(a2.barcode); await waitParcel('DEMO00000002',{location_id:a2.id});
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('#selected-count')?.textContent==='2' && document.querySelector('#receipt-courier')?.value==='2');
    assert(await page.locator('#receipt-place').isChecked());
    await page.locator('#logout').click();
    await page.locator('#login-view').waitFor({state:'visible'});
    await page.locator('#app-password').fill('local-e2e-password-only');
    await page.locator('#login-button').click();
    await page.waitForFunction(()=>document.querySelector('#selected-count')?.textContent==='2' && document.querySelector('#receipt-courier')?.value==='2');
    assert(await page.locator('#receipt-place').isChecked());
    await shot('sps-receipt-mobile');
    await page.locator('#prepare').click();
    await page.locator('#confirm-dialog').waitFor({state:'visible'});
    assert.equal(await page.locator('#courier').inputValue(),'2');
    await page.locator('#courier-password').fill('demo');
    await page.locator('#confirm-submit').click();
    await page.locator('#new-receipt').waitFor({state:'visible'});
    await waitParcel('DEMO00000001',{carrier_status:'accepted',location_id:a1.id});
    data=await snapshot(); assert.equal(data.settings.last_courier_id,'2');
    step('Receive + place + draft reload + explicitly selected second courier work.');
    await page.locator('#new-receipt').click();
    await scan('DEMO00000003');
    await page.waitForFunction(()=>document.querySelector('#receipt-courier').value==='2');
    await page.locator('#courier-warning').waitFor({state:'visible'});
    step('Next receipt reuses last successful courier and shows order warning.');
    await openView('store');
    await scan('DEMO00000001');
    await page.locator('#manual-destination').waitFor({state:'visible'});
    assert((await page.locator('#warehouse-panel').innerText()).includes('A1'));
    await scan(a2.barcode); await waitParcel('DEMO00000001',{location_id:a2.id});
    await scan(a2.barcode);
    await page.getByRole('button',{name:'Inventúra miesta',exact:true}).click();
    await scan('DEMO00000001');
    await page.waitForFunction(()=>document.querySelector('.summary-strip')?.textContent.includes('1 z 2'));
    await scan('DEMO00000002');
    await page.waitForFunction(()=>document.querySelector('.summary-strip')?.textContent.includes('2 z 2'));
    await page.getByRole('button',{name:'Ukončiť inventúru',exact:true}).click();
    await page.getByRole('button',{name:'Presun medzi miestami',exact:true}).click();
    await page.locator('#bulk-source').selectOption(a2.id);
    await page.locator('#bulk-target').selectOption(a1.id);
    await page.getByRole('button',{name:'Skontrolovať presun',exact:true}).click();
    await page.locator('#confirm-action-dialog').getByRole('button',{name:'Balíky sú presunuté',exact:true}).click();
    await waitParcel('DEMO00000001',{location_id:a1.id});
    await waitParcel('DEMO00000002',{location_id:a1.id});
    step('Independent movement, shelf contents, inventory and atomic bulk move work.');
    await openView('settings');
    await page.locator('#setting-courier_warning').uncheck();
    await page.waitForFunction(async()=>!(await (await fetch('./api/warehouse')).json()).settings.courier_warning);
    await page.locator('#setting-photos').check();
    await page.waitForFunction(async()=>(await (await fetch('./api/warehouse')).json()).settings.photos);
    await page.locator('#setting-return_staging').check();
    await page.waitForFunction(async()=>(await (await fetch('./api/warehouse')).json()).settings.return_staging);
    await openView('receipt');
    assert(await page.locator('#courier-warning').isHidden());
    await openView('store');
    await scan('DEMO00000001');
    await page.getByRole('button',{name:'Odfotiť',exact:true}).click();
    await page.locator('#photo-file').setInputFiles(photoFixture);
    await page.locator('#photo-save:not([disabled])').waitFor();
    await page.locator('#photo-save').click();
    await page.locator('#photo-dialog').waitFor({state:'hidden'});
    await page.waitForFunction(async()=>(await (await fetch('./api/warehouse')).json()).parcels.find(p=>p.number==='DEMO00000001')?.photo_url);
    step('Optional photo upload and courier-warning setting work.');
    await openView('pickup');
    await page.locator('#pickup-pin').fill('000001');
    await page.locator('#pickup-form').getByRole('button',{name:'Nájsť',exact:true}).click();
    await page.locator('#pickup-confirm').waitFor();
    assert((await page.locator('#warehouse-panel').innerText()).includes('A1'));
    assert(await page.locator('#warehouse-panel .parcel-photo').isVisible());
    await scan('DEMO00000001');
    await page.waitForFunction(()=>document.querySelector('#pickup-confirm')?.disabled===false);
    await scan('DEMO00000002');
    await page.waitForFunction(()=>document.querySelector('#pickup-confirm')?.disabled===true);
    await scan('DEMO00000001');
    await page.waitForFunction(()=>document.querySelector('#pickup-confirm')?.disabled===false);
    await shot('sps-pickup-mobile');
    await page.locator('#pickup-confirm').click();
    await waitParcel('DEMO00000001',{carrier_status:'delivered',location_id:null});
    await waitReady('pickup');
    step('Pickup shows location/photo, rejects wrong scan after right scan, confirms delivery.');
    await page.locator('#pickup-pin').fill('111111');
    await page.locator('#pickup-form').getByRole('button',{name:'Nájsť',exact:true}).click();
    await page.locator('#pickup-cod-confirmed').waitFor();
    await scan('DEMOSTORED01');
    assert(await page.locator('#pickup-confirm').isDisabled());
    await page.locator('#pickup-cod-confirmed').check();
    await page.locator('#pickup-confirm:not([disabled])').waitFor();
    await page.locator('#pickup-confirm').click();
    const receipt=page.getByRole('link',{name:'Otvoriť / vytlačiť doklad',exact:true});
    await receipt.waitFor();
    const pdfResponse=await context.request.get(new URL(await receipt.getAttribute('href'),base).href);
    assert.equal(pdfResponse.status(),200);
    assert((await pdfResponse.body()).subarray(0,5).equals(Buffer.from('%PDF-')));
    step('COD requires explicit confirmation and produces authenticated SPS PDF receipt.');
    await openView('returns');
    await page.waitForFunction(()=>document.querySelector('#warehouse-panel').textContent.includes('DEMOEXPIRED01'));
    await scan('DEMOBLOCKED01');
    assert.equal(await page.locator('#return-confirm').count(),0);
    await scan('DEMOEXPIRED01');
    await page.locator('#return-courier').waitFor();
    await page.getByRole('button',{name:'Označiť ako pripravené vopred',exact:true}).click();
    await waitParcel('DEMOEXPIRED01',{staged:true});
    await page.locator('#return-confirm').waitFor({state:'hidden'});
    await scan('DEMOEXPIRED01');
    await page.locator('#return-courier').waitFor();
    await page.locator('#return-courier').selectOption('2');
    await page.locator('#return-confirm').click();
    await page.locator('#confirm-action-dialog').getByRole('button',{name:'Kuriér prevzal balíky',exact:true}).click();
    await waitParcel('DEMOEXPIRED01',{carrier_status:'returned',location_id:null});
    await waitReady('returns');
    step('Optional staging requires a new physical scan; courier handover works and SPS-blocked parcel cannot be selected.');
    await openView('locations');
    const row=page.locator('.location-row').filter({hasText:'A2'});
    await row.getByRole('button',{name:'Premenovať',exact:true}).click();
    await page.getByRole('textbox',{name:'Nový názov miesta',exact:true}).fill('Horná polica');
    await page.getByRole('button',{name:'Uložiť názov',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#warehouse-panel').textContent.includes('Horná polica'));
    data=await snapshot(); assert.equal(data.locations.find(p=>p.id===a2.id).barcode,a2.barcode);
    await page.evaluate(()=>{window.print=()=>{window.__printed=true;};});
    await page.getByRole('button',{name:'Tlačiť všetky',exact:true}).click();
    assert.equal(await page.locator('#print-labels svg').count(),3);
    await page.emulateMedia({media:'print'});
    await page.pdf({path:path.join(output, 'sps-labels-test.pdf'),preferCSSPageSize:true,printBackground:true});
    await page.locator('#print-labels svg').first().screenshot({path:path.join(output, 'location-barcode.png')});
    await fs.writeFile(path.join(output, 'expected-barcode.txt'),data.locations[0].barcode);
    await page.emulateMedia({media:'screen'});
    await shot('sps-locations-mobile');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.setViewportSize({width:1360,height:900});
    await shot('sps-locations-desktop');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    step('Stable barcode after rename, print PDF, mobile/desktop layout and console checks pass.');
    step('BROWSER SMOKE PASSED');
  } catch(error) {
    await shot('sps-e2e-failure').catch(()=>{});
    step('FAIL '+error.stack);
    step((await page.locator('body').innerText()).slice(-10000));
    step('PAGE ERRORS '+JSON.stringify(errors));
    process.exitCode=1;
  } finally { await browser.close(); }
})();
